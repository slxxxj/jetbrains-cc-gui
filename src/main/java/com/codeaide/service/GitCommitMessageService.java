    /**
     * Fan-out generation for large change sets: each batch of inventory lines
     * gets a parallel summary agent; the summaries are merged into a single
     * commit message by one final request. Blocks the calling thread until done;
     * the timeout guard and its cleanups bound the wait.
     */
    private void generateWithFanOut(
            List<String> inventory,
            int batchSize,
            int maxParallel,
            TimeoutGuard guardedCallback
    ) throws IOException {
        JsonObject commitAiConfig = getCommitAiConfig();
        String effectiveProvider = getResolvedCommitAiProvider(commitAiConfig);
        if (effectiveProvider == null) {
            guardedCallback.onError(localized("commit.noAvailableProvider"));
            return;
        }

        List<List<String>> batches = new ArrayList<>();
        for (int i = 0; i < inventory.size(); i += batchSize) {
            batches.add(inventory.subList(i, Math.min(i + batchSize, inventory.size())));
        }
        LOG.info("Commit fan-out: " + inventory.size() + " files in " + batches.size()
                + " batches, maxParallel=" + maxParallel);

        reportStage("commit.stage.connecting");
        ExecutorService pool = Executors.newFixedThreadPool(Math.min(maxParallel, batches.size()));
        guardedCallback.addTimeoutCleanup(pool::shutdownNow);
        try {
            List<CompletableFuture<String>> futures = new ArrayList<>();
            for (int i = 0; i < batches.size(); i++) {
                final int batchIndex = i;
                final List<String> batch = batches.get(i);
                futures.add(CompletableFuture.supplyAsync(
                        () -> summarizeBatch(batch, batchIndex, batches.size(), inventory.size(), commitAiConfig, effectiveProvider),
                        pool));
            }

            List<String> summaries = new ArrayList<>();
            int finished = 0;
            for (CompletableFuture<String> future : futures) {
                String summary = null;
                try {
                    summary = future.join();
                } catch (Exception e) {
                    LOG.warn("Batch summary agent failed: " + e.getMessage());
                }
                finished++;
                reportStage("commit.stage.batch", finished, futures.size());
                if (summary != null && !summary.isEmpty()) {
                    summaries.add(summary);
                }
            }

            if (summaries.isEmpty()) {
                guardedCallback.onError(localized("commit.callApiFailed"));
                return;
            }

            reportStage("commit.stage.merging");
            String merged;
            try {
                merged = requestOnce(buildMergePrompt(summaries, inventory), commitAiConfig, effectiveProvider);
            } catch (InterruptedException e) {
                // Interrupted by the timeout guard / cancellation cleanup; the
                // guard has already delivered the outcome to the delegate.
                Thread.currentThread().interrupt();
                return;
            }
            guardedCallback.onSuccess(merged);
        } finally {
            pool.shutdownNow();
        }
    }

    /**
     * Summarize one batch of inventory lines for later merging. Returns "" when
     * the agent request failed (tolerated — the remaining batches still produce
     * a commit message).
     */
    private String summarizeBatch(
            List<String> batchLines,
            int index,
            int total,
            int totalFiles,
            JsonObject commitAiConfig,
            String provider
    ) {
        try {
            return requestOnce(buildBatchSummaryPrompt(batchLines, index, total, totalFiles), commitAiConfig, provider);
        } catch (Exception e) {
            LOG.warn("Batch " + (index + 1) + "/" + total + " summary failed: " + e.getMessage());
            return "";
        }
    }

    /**
     * Run one provider request and block until it completes. Used by the
     * fan-out batch agents and the merge request.
     */
    private String requestOnce(String prompt, JsonObject commitAiConfig, String provider)
            throws IOException, InterruptedException {
        CompletableFuture<String> future = new CompletableFuture<>();
        CommitMessageCallback single = new CommitMessageCallback() {
            @Override
            public void onSuccess(String commitMessage) {
                future.complete(commitMessage);
            }

            @Override
            public void onError(String error) {
                future.completeExceptionally(new RuntimeException(error));
            }
        };
        if (PROVIDER_CODEX.equals(provider)) {
            callCodexAPI(prompt, getResolvedCommitAiModel(commitAiConfig, PROVIDER_CODEX), single);
        } else {
            callClaudeAPI(prompt, getResolvedCommitAiModel(commitAiConfig, PROVIDER_CLAUDE), single);
        }
        try {
            return future.get();
        } catch (InterruptedException e) {
            future.cancel(true);
            throw e;
        } catch (ExecutionException e) {
            Throwable cause = e.getCause();
            throw new IOException(cause != null ? cause.getMessage() : e.getMessage());
        }
    }

    /**
     * Build the per-batch summary prompt from inventory lines. The output
     * contract ("type: x" first line + bullet points, no tags) is deliberately
     * tag-free so the summaries pass the commit-message cleanup intact.
     */
    private String buildBatchSummaryPrompt(List<String> batchLines, int index, int total, int totalFiles) {
        StringBuilder prompt = new StringBuilder();
        prompt.append("你是变更分析助手。整个提交涉及 ").append(totalFiles)
                .append(" 个文件的变更，已按文件分为 ").append(total)
                .append(" 批，以下是第 ").append(index + 1)
                .append(" 批的变更清单（格式：状态 路径 (+增/-删)，A=新增 M=修改 D=删除）。\n\n");
        prompt.append("请极简概括这批文件改动的意图，供后续合并生成 commit message：\n");
        prompt.append("1. 第一行只写：type: <类型>（类型从 feat / fix / refactor / perf / docs / style / test / build / ci / chore / revert 中选一个最主要的）\n");
        prompt.append("2. 第二行起用 1~3 个 \"- \" 要点概括这批变更做了什么\n");
        prompt.append("3. 除此之外不输出任何内容（不要分析过程、不要解释、不要代码围栏）\n");
        String languageName = LanguageConfigService.getLanguageDisplayName(getCommitOutputLanguage());
        prompt.append("4. 要点必须使用 ").append(languageName).append(" 撰写\n\n");
        for (String line : batchLines) {
            prompt.append(line).append("\n");
        }
        return prompt.toString();
    }

    /**
     * Build the merge prompt that reduces the full inventory and all batch
     * summaries into one conventional commit message.
     */
    private String buildMergePrompt(List<String> summaries, List<String> inventory) {
        StringBuilder prompt = new StringBuilder();
        prompt.append(BUILTIN_COMMIT_PROMPT);
        appendUserAndProjectPrompts(prompt);
        appendOutputLanguageRequirement(prompt);

        prompt.append("\n\n---\n\n");
        prompt.append("本次提交涉及 ").append(inventory.size())
                .append(" 个文件的变更。完整变更清单如下（格式：状态 路径 (+增/-删)，A=新增 M=修改 D=删除）：\n\n");
        prompt.append(cappedInventoryText(inventory));
        prompt.append("\n\n各批分析代理的概括结果（共 ").append(summaries.size()).append(" 批）：\n\n");
        for (int i = 0; i < summaries.size(); i++) {
            prompt.append("【第 ").append(i + 1).append(" 批】\n");
            prompt.append(summaries.get(i)).append("\n\n");
        }
        prompt.append("请将以上变更归纳为一个逻辑整体，选择最主要的一个 type，生成一条统一的 commit message。");

        appendOutputFormatRequirements(prompt);
        return prompt.toString();
    }

    /**
     * Render the inventory for prompts, capped at {@link #MAX_INVENTORY_CHARS}
     * with an overflow note so huge change sets stay within model limits.
     */
    private String cappedInventoryText(List<String> inventory) {
        StringBuilder text = new StringBuilder();
        int shown = 0;
        for (String line : inventory) {
            if (text.length() + line.length() + 1 > MAX_INVENTORY_CHARS) {
                break;
            }
            text.append(line).append("\n");
            shown++;
        }
        if (shown < inventory.size()) {
            text.append("… 其余 ").append(inventory.size() - shown).append(" 个文件从略");
        }
        return text.toString();
    }

    /**
     * Build the per-file change inventory ("M path (+a/-d)") for every change.
     * Computed locally without any AI call. Files that fail to load are listed
     * without line counts. Extracted for tests.
     */
    protected List<String> buildChangeInventory(List<Change> changes) {
        List<String> inventory = new ArrayList<>(changes.size());
        for (Change change : changes) {
            try {
                FilePath filePath = ChangesUtil.getFilePath(change);
                Change.Type changeType = change.getType();

                if (changeType == Change.Type.NEW) {
                    String content = readContentSafely(change.getAfterRevision());
                    inventory.add("A  " + filePath.getPath() + " (+" + countLines(content) + ")");
                } else if (changeType == Change.Type.DELETED) {
                    String content = readContentSafely(change.getBeforeRevision());
                    inventory.add("D  " + filePath.getPath() + " (-" + countLines(content) + ")");
                } else {
                    String before = readContentSafely(change.getBeforeRevision());
                    String after = readContentSafely(change.getAfterRevision());
                    if (before != null && after != null
                            && before.length() <= MAX_FILE_CONTENT_LENGTH
                            && after.length() <= MAX_FILE_CONTENT_LENGTH) {
                        int[] counts = countLineChanges(before, after);
                        if (counts[0] >= 0) {
                            inventory.add("M  " + filePath.getPath() + " (+" + counts[0] + "/-" + counts[1] + ")");
                        } else {
                            inventory.add("M  " + filePath.getPath() + " (+?/-?)");
                        }
                    } else {
                        inventory.add("M  " + filePath.getPath());
                    }
                }
            } catch (Exception e) {
                LOG.warn("Failed to inspect change for inventory: " + e.getMessage());
            }
        }
        return inventory;
    }

    /**
     * Build the per-file detail section appended after the generated commit
     * message, or null when the inventory is empty (nothing meaningful to show).
     */
    private String buildFileDetailSection(List<String> inventory) {
        if (inventory.isEmpty()) {
            return null;
        }
        StringBuilder detail = new StringBuilder();
        detail.append("\n\n").append(localized("commit.detailHeader", inventory.size()));
        int shown = Math.min(inventory.size(), MAX_DETAIL_LINES);
        for (int i = 0; i < shown; i++) {
            detail.append("\n").append(inventory.get(i));
        }
        if (inventory.size() > shown) {
            detail.append("\n").append(localized("commit.detailTruncated", inventory.size() - shown));
        }
        return detail.toString();
    }

    private static String readContentSafely(ContentRevision revision) {
        if (revision == null) {
            return null;
        }
        try {
            return revision.getContent();
        } catch (Exception e) {
            return null;
        }
    }

    private static int countLines(String content) {
        if (content == null || content.isEmpty()) {
            return 0;
        }
        return content.split("\n").length;
    }

    /**
     * Count added/removed lines between two file versions using an LCS on
     * lines (two-row DP, O(min(n,m)) memory). Returns {added, deleted}, or
     * {-1, -1} when the inputs are too large to compare precisely.
     */
    static int[] countLineChanges(String before, String after) {
        String[] beforeLines = before.split("\n");
        String[] afterLines = after.split("\n");
        if ((long) beforeLines.length * (long) afterLines.length > MAX_LCS_CELLS) {
            return new int[]{-1, -1};
        }
        int lcs = lcsLength(beforeLines, afterLines);
        return new int[]{afterLines.length - lcs, beforeLines.length - lcs};
    }

    private static int lcsLength(String[] a, String[] b) {
        // Keep b the shorter dimension for memory
        if (a.length < b.length) {
            String[] tmp = a;
            a = b;
            b = tmp;
        }
        int[] prev = new int[b.length + 1];
        int[] curr = new int[b.length + 1];
        for (int i = 1; i <= a.length; i++) {
            String ai = a[i - 1];
            for (int j = 1; j <= b.length; j++) {
                curr[j] = ai.equals(b[j - 1]) ? prev[j - 1] + 1 : Math.max(prev[j], curr[j - 1]);
            }
            int[] tmp = prev;
            prev = curr;
            curr = tmp;
            java.util.Arrays.fill(curr, 0);
        }
        return prev[b.length];
    }

