    /**
     * Generate a commit message.
     *
     * @param changes  The selected file changes
     * @param callback The callback interface
     * @return a handle to cancel the in-flight generation
     */
    public GenerationHandle generateCommitMessage(
            @NotNull Collection<Change> changes,
            @NotNull CommitMessageCallback callback
    ) {
        return generateCommitMessage(changes, callback, null);
    }

    /**
     * Generate a commit message with optional stage progress reporting.
     *
     * @param changes          The selected file changes
     * @param callback         The callback interface
     * @param progressCallback Optional stage progress callback (nullable)
     * @return a handle to cancel the in-flight generation
     */
    public GenerationHandle generateCommitMessage(
            @NotNull Collection<Change> changes,
            @NotNull CommitMessageCallback callback,
            ProgressCallback progressCallback
    ) {
        this.progressCallback = progressCallback;

        List<Change> changeList = new ArrayList<>(changes);
        int batchSize = getCommitAgentBatchSize();
        int maxParallel = getCommitAgentMaxParallel();
        int batchCount = batchCount(changeList.size(), batchSize);
        boolean fanOut = batchCount > 1;

        reportStage("commit.stage.collecting");
        // Per-file change inventory (status + line counts), computed locally and
        // therefore instant. It feeds the detail section appended to the final
        // message and, for large change sets, the fan-out agents (compact input
        // keeps them fast).
        List<String> inventory = buildChangeInventory(changeList);
        String fileDetail = isCommitIncludeFileDetail() ? buildFileDetailSection(inventory) : null;
        CommitMessageCallback delegate = fileDetail == null ? callback : new CommitMessageCallback() {
            @Override
            public void onSuccess(String commitMessage) {
                callback.onSuccess(commitMessage + fileDetail);
            }

            @Override
            public void onError(String error) {
                callback.onError(error);
            }
        };

        TimeoutGuard guardedCallback = new TimeoutGuard(delegate, localized("commit.generateTimeout"));
        guardedCallback.arm(fanOut
                ? computeFanOutTimeoutMs(batchCount, maxParallel)
                : getGenerationTimeoutMs());
        // Interrupts every bridge created by this generation (single request,
        // fan-out batches and the merge request alike).
        guardedCallback.addTimeoutCleanup(this::runBridgeCleanups);
        try {
            if (fanOut) {
                // Large change set: one summary agent per batch of files running
                // in parallel, then one merge request — avoids the single-request
                // timeout that huge diffs would hit.
                generateWithFanOut(inventory, batchSize, maxParallel, guardedCallback);
            } else {
                // 1. Generate git diff
                String diff = generateGitDiff(changeList);
                if (diff.isEmpty()) {
                    guardedCallback.onError(localized("commit.noChangesFound"));
                    return () -> { };
                }

                // 2. Build the full prompt (built-in + user's additional prompt + diff)
                String fullPrompt = buildFullPrompt(diff);

                // 3. Call the AI SDK
                callAIService(fullPrompt, guardedCallback);
            }

        } catch (IOException e) {
            LOG.warn("AI service call failed", e);
            String message = e.getMessage();
            guardedCallback.onError(localized("commit.callApiFailed") + ": " + (message != null ? message : e.getClass().getSimpleName()));
        } catch (Exception e) {
            LOG.error("Failed to generate commit message", e);
            String message = e.getMessage();
            guardedCallback.onError(message != null ? message : e.getClass().getSimpleName());
        }
        return () -> guardedCallback.fail(localized("commit.generateCancelled"));
    }

