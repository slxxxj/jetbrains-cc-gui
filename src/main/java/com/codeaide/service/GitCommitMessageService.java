    /**
     * Fan-out timeout: a per-wave allowance for ceil(batches / parallel) waves
     * plus a base margin covering daemon cold starts and the merge request,
     * capped at {@link #MAX_FAN_OUT_TIMEOUT_MS}.
     */
    static long computeFanOutTimeoutMs(int batchCount, int maxParallel) {
        int waves = (int) Math.ceil(batchCount / (double) Math.max(1, maxParallel));
        return Math.min(MAX_FAN_OUT_TIMEOUT_MS,
                FAN_OUT_BASE_TIMEOUT_MS + FAN_OUT_PER_WAVE_TIMEOUT_MS * waves);
    }

    private static int batchCount(int changeCount, int batchSize) {
        if (changeCount <= 0) {
            return 0;
        }
        return (int) Math.ceil(changeCount / (double) Math.max(1, batchSize));
    }

