    /**
     * Build the full prompt.
     * Logic: built-in prompt + user's additional prompt + project-level additional prompt (highest priority)
     * + output language requirement (follows the configured UI language) + git diff.
     */
    private String buildFullPrompt(String diff) {
        StringBuilder prompt = new StringBuilder();

        // 1. Built-in commit prompt
        prompt.append(BUILTIN_COMMIT_PROMPT);

        // 2-3. User's global + project-level additional prompts
        appendUserAndProjectPrompts(prompt);

        // 4. Output language requirement (follows the current UI language setting; mandatory)
        appendOutputLanguageRequirement(prompt);

        // 5. Git diff content
        prompt.append("\n\n---\n\n");
        prompt.append("以下是 git diff 信息，请根据以上规则生成 commit message：\n\n");
        prompt.append("```diff\n");
        prompt.append(diff);
        prompt.append("\n```");

        // 6. Output format requirements (enforce XML tag wrapping for easy parsing)
        appendOutputFormatRequirements(prompt);

        return prompt.toString();
    }

    /**
     * Append the user's global additional prompt and the project-level additional
     * prompt (highest priority), when configured.
     */
    private void appendUserAndProjectPrompts(StringBuilder prompt) {
        // User's global additional prompt (if any)
        String userAdditionalPrompt = getUserAdditionalPrompt();
        if (!userAdditionalPrompt.isEmpty()) {
            prompt.append("\n\n## 用户附加要求（优先遵循）\n\n");
            prompt.append("以下是用户的额外要求，请在生成 commit message 时优先考虑这些要求：\n\n");
            prompt.append(userAdditionalPrompt);
        }

        // Project-level additional prompt (highest priority)
        String projectAdditionalPrompt = getProjectAdditionalPrompt();
        if (!projectAdditionalPrompt.isEmpty()) {
            prompt.append("\n\n## 项目专属要求\n\n");
            prompt.append("以下是当前项目的专属要求，与上述用户附加要求同时生效。当两者矛盾时，以此处项目要求为准：\n\n");
            prompt.append(projectAdditionalPrompt);
        }
    }

